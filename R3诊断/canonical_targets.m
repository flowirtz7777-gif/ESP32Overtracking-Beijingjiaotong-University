function tg = canonical_targets()
%CANONICAL_TARGETS  固定验收目标集（世界坐标系，冻结，跨方案不变）。
%
%   tg = canonical_targets()
%
%   输出 tg (struct array)，字段：
%     name : 目标名（字符串）
%     xy   : [x, y] 世界坐标 (m)
%
%   ⚠️ 这个集合是**冻结**的：一旦确定，任何方案对比都必须用它，
%      不允许各方案各自现生成目标点（这是 v1.0.2 上一轮踩的方法论坑——
%      对比脚本用 local_make_fixed_targets 沿右沿现造点，导致 summary 里
%      的 R3 接触时刻 17.92s 和复盘文档的 16.24–18.12s 对不上，
%      结论无法横向比较）。
%
%   行 1 = canonical R3：来自 `工作复盘`/CLAUDE.md §4.3 固化的反例。
%     R3 = (15.162112188, 34.264469347)
%     在 pid_scenario_20260530_020804.csv 工况下，挂车车身约在
%     t≈16.2–18.1s 覆盖该点；它位于弯道出弯处，是「出弯阶段提前量不足」
%     的标准验收样例。
%
%   其余行是围绕 R3 的少量固定参考点（确定性、手工冻结，不随机），
%   用于看「内切窄条」附近的判内边界，不参与 canonical 提前量结论。

    tg = struct('name', {}, 'xy', {});

    tg(end+1) = struct('name', 'R3',     'xy', [15.162112188,       34.264469347]);       % canonical 反例（唯一验收基准）
    tg(end+1) = struct('name', 'R3_a',   'xy', [15.162112188 - 0.6, 34.264469347 + 0.6]); % R3 附近上下文探针（不参与结论）
    tg(end+1) = struct('name', 'R3_b',   'xy', [15.162112188 + 0.6, 34.264469347 - 0.6]); % R3 附近上下文探针（不参与结论）
end
