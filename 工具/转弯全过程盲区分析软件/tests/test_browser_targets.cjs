const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
(async()=>{
  const root=path.resolve(__dirname,'..');
  const project=path.resolve(root,'..','..');
  const out=path.join(root,'logs','browser_targets_'+Date.now());fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const errors=[];
  try{
    const page=await browser.newPage({viewport:{width:1600,height:1080},acceptDownloads:true});
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.join(root,'index.html')).href);
    await page.locator('#scenario-file').setInputFiles(path.join(project,'工具','alpha一阶保持仿真','scenarios','pid_scenario_20260530_020804.csv'));
    await page.waitForFunction(()=>document.getElementById('load-status').textContent.startsWith('已导入场景:'));
    await page.locator('#cfg-file').setInputFiles(path.join(root,'CFG配置','default_cfg.json'));
    await page.waitForFunction(()=>document.getElementById('load-status').textContent.startsWith('已导入 CFG:'));
    await page.locator('#spacing').fill('0.35');await page.locator('#max-targets').fill('90');
    await page.locator('#build-targets').click();
    await page.waitForFunction(()=>document.getElementById('load-status').textContent.startsWith('已生成并分析'),null,{timeout:180000});
    let state=await page.evaluate(()=>({targets,logs:logRows,source:document.getElementById('source-label').textContent}));
    assert.equal(state.targets.length,90);
    for(const group of ['interior','boundary','negative']) assert.equal(state.targets.filter(t=>t.sampleGroup===group).length,30);
    assert(state.targets.filter(t=>t.sampleGroup==='negative').every(t=>t.trueContactIdx===null || Number.isNaN(t.trueContactIdx)));
    assert(state.logs.filter(r=>r.truth_label==='NO_CONTACT_IN_RECORD').every(r=>['FALSE_POSITIVE','CORRECT_REJECTION','END_TRUNCATED'].includes(r.event)));
    assert(state.logs.some(r=>r.nearest_contact_edge==='FRONT'));
    assert(state.logs.filter(r=>r.nearest_contact_edge==='FRONT').every(r=>r.event==='FRONT_CONTACT_IGNORED'));
    assert.equal(state.logs.filter(r=>r.event==='POLYW_NO_HIT').length,0,'Front-only misses excluded');
    assert((await page.locator('#summary-grid').innerText()).includes('前沿忽略'));
    const targetDownload=page.waitForEvent('download');await page.locator('#export-targets').click();
    const download=await targetDownload;const targetCsv=path.join(out,'web_targets.csv');await download.saveAs(targetCsv);
    const logDownload=page.waitForEvent('download');await page.locator('#export-log').click();
    const logCsv=path.join(out,'web_log.csv');await (await logDownload).saveAs(logCsv);
    const original=JSON.stringify(state.targets.map(t=>[t.x,t.y,t.sampleGroup]));
    await page.locator('#target-file').setInputFiles(targetCsv);
    await page.waitForFunction(()=>document.getElementById('load-status').textContent.startsWith('已导入固定目标点:'),null,{timeout:180000});
    const imported=await page.evaluate(()=>targets.map(t=>[t.x,t.y,t.sampleGroup]));
    const originalCoordinates=JSON.parse(original);
    assert.equal(imported.length,originalCoordinates.length);
    imported.forEach((r,i)=>assert(Math.abs(r[0]-originalCoordinates[i][0])<=1e-6 && Math.abs(r[1]-originalCoordinates[i][1])<=1e-6 && r[2]===originalCoordinates[i][2]));
    await page.locator('#time-slider').evaluate(el=>{el.value='800';el.dispatchEvent(new Event('input',{bubbles:true}));});
    assert.equal(await page.evaluate(()=>currentIndex),800,'Time slider updates rendered vehicle state');
    await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
    const canvasPixels=await page.evaluate(()=>{
      const c=document.getElementById('scene-diagnosis'),ctx=c.getContext('2d');
      const data=ctx.getImageData(0,0,c.width,c.height).data;const colors=new Set();
      for(let i=0;i<data.length;i+=64)colors.add(data[i]+','+data[i+1]+','+data[i+2]);
      return colors.size;
    });
    assert(canvasPixels>10,'Canvas must contain rendered data');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
    await page.locator('.canvas-wrap').screenshot({path:path.join(out,'mobile_canvas.png')});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
    assert(!overflow,'Mobile page must not overflow horizontally');
    const panelsSeparated=await page.evaluate(()=>document.getElementById('diagnosis-panel').getBoundingClientRect().bottom<=document.querySelector('.controls').getBoundingClientRect().top);
    assert(panelsSeparated,'Playback controls must not cover canvas status text');
    await page.setViewportSize({width:1600,height:1080});
    await page.locator('#use-default').click();
    await page.waitForFunction(()=>document.getElementById('load-status').textContent.startsWith('已载入内置示例工况'),null,{timeout:180000});
    const switched=await page.evaluate(()=>{
      const actual=TargetSampling.firstContacts(targets.map(t=>[t.x,t.y]),data,cfg,Number(document.getElementById('grid-size').value));
      return targets.every((t,i)=>Number.isFinite(actual[i]) ? t.trueContactIdx===actual[i] : !Number.isFinite(t.trueContactIdx));
    });
    assert(switched,'Switching scenes must recompute all truth labels');
    assert.equal(await page.evaluate(()=>targets.length),90);
    await page.locator('#target-mode').selectOption('boundary');
    await page.locator('#max-targets').fill('60');
    await page.locator('#build-targets').click();
    await page.waitForFunction(()=>document.getElementById('load-status').textContent.startsWith('已生成并分析'),null,{timeout:180000});
    assert(await page.evaluate(()=>targets.every(t=>t.sampleGroup==='boundary')),'Legacy target mode');
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(out,'report.json'),JSON.stringify({passed:true,pageErrors:errors,canvasColors:canvasPixels,
      targetCount:90,groups:{interior:30,boundary:30,negative:30},targetCsv,logCsv,source:state.source},null,2));
    console.log('PASSED browser target generation/import/export/scene switch/legacy mode and desktop-mobile checks: '+out);
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
